package cli

import (
	"context"
	"fmt"
	"io"
	"sort"
	"strings"
)

var completionShells = []string{"bash", "zsh", "fish", "powershell"}

func completionCommand() command {
	return command{
		name:    "completion",
		summary: "Print a shell completion script (bash, zsh, fish, powershell)",
		args:    "<bash|zsh|fish|powershell>",
		long: `Prints a completion script for the given shell. The scripts are generated from
the same command table as --help, so they never drift from the real flags.

Install:
  bash        source <(teardown completion bash)            # or save to /etc/bash_completion.d/teardown
  zsh         teardown completion zsh > "${fpath[1]}/_teardown"
  fish        teardown completion fish > ~/.config/fish/completions/teardown.fish
  powershell  teardown completion powershell | Out-String | Invoke-Expression   # add to $PROFILE to keep it`,
		examples: []string{
			"source <(teardown completion bash)",
			"teardown completion powershell | Out-String | Invoke-Expression",
		},
		register: func(*flagSet) runner {
			return func(_ context.Context, env Env, pos []string) int {
				if len(pos) != 1 {
					return usageError(env, "completion", "expected one shell: %s", strings.Join(completionShells, ", "))
				}
				var sb strings.Builder
				switch pos[0] {
				case "bash":
					writeBash(&sb)
				case "zsh":
					writeZsh(&sb)
				case "fish":
					writeFish(&sb)
				case "powershell", "pwsh":
					writePowerShell(&sb)
				default:
					return usageError(env, "completion", "unknown shell %q (choose one of: %s)", pos[0], strings.Join(completionShells, ", "))
				}
				if _, err := io.WriteString(env.Stdout, sb.String()); err != nil {
					return failure(env, "completion", err)
				}
				return exitOK
			}
		},
	}
}

// completionInfo is the data every script is generated from.
type completionInfo struct {
	name    string
	summary string
	flags   []flagSpec
	// positional is "file" for commands that take files, "shell" for completion, "" otherwise.
	positional string
}

func completionData() []completionInfo {
	var out []completionInfo
	for _, c := range commands() {
		fs := newFlagSet(c.name)
		c.register(fs)
		info := completionInfo{name: c.name, summary: c.summary, flags: fs.specs}
		switch {
		case c.name == "completion":
			info.positional = "shell"
		case strings.Contains(c.args, "file") || c.args == "<a> <b>":
			info.positional = "file"
		}
		out = append(out, info)
	}
	return out
}

// flagWords returns every spelling of a flag.
func (s flagSpec) words() []string {
	w := []string{"--" + s.name}
	if s.short != "" {
		w = append(w, "-"+s.short)
	}
	return w
}

// valueKinds maps each flag spelling to the values or kind it takes (shared by
// every command: the flags that appear in several commands agree).
func valueKinds(data []completionInfo) (allowed map[string][]string, files, dirs []string) {
	allowed = map[string][]string{}
	for _, c := range data {
		for _, f := range c.flags {
			for _, w := range f.words() {
				switch {
				case len(f.allowed) > 0:
					allowed[w] = f.allowed
				case f.file:
					files = append(files, w)
				case f.dir:
					dirs = append(dirs, w)
				}
			}
		}
	}
	sort.Strings(files)
	sort.Strings(dirs)
	return allowed, files, dirs
}

func allFlagWords(c completionInfo) []string {
	var w []string
	for _, f := range c.flags {
		w = append(w, f.words()...)
	}
	return append(w, "-h", "--help")
}

func writeBash(sb *strings.Builder) {
	data := completionData()
	allowed, files, dirs := valueKinds(data)
	names := make([]string, 0, len(data)+1)
	for _, c := range data {
		names = append(names, c.name)
	}
	names = append(names, "help")

	sb.WriteString("# bash completion for teardown (generated by `teardown completion bash`)\n")
	sb.WriteString("_teardown() {\n    local cur prev cmd opts\n")
	sb.WriteString("    cur=\"${COMP_WORDS[COMP_CWORD]}\"\n    prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n")
	fmt.Fprintf(sb, "    if [[ $COMP_CWORD -eq 1 ]]; then\n        COMPREPLY=( $(compgen -W %q -- \"$cur\") )\n        return\n    fi\n", strings.Join(names, " "))
	sb.WriteString("    cmd=\"${COMP_WORDS[1]}\"\n    case \"$prev\" in\n")
	keys := make([]string, 0, len(allowed))
	for k := range allowed {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(sb, "        %s) COMPREPLY=( $(compgen -W %q -- \"$cur\") ); return ;;\n", k, strings.Join(allowed[k], " "))
	}
	if len(files) > 0 {
		fmt.Fprintf(sb, "        %s) COMPREPLY=( $(compgen -f -- \"$cur\") ); return ;;\n", strings.Join(files, "|"))
	}
	if len(dirs) > 0 {
		fmt.Fprintf(sb, "        %s) COMPREPLY=( $(compgen -d -- \"$cur\") ); return ;;\n", strings.Join(dirs, "|"))
	}
	sb.WriteString("    esac\n    case \"$cmd\" in\n")
	for _, c := range data {
		fmt.Fprintf(sb, "        %s) opts=%q ;;\n", c.name, strings.Join(allFlagWords(c), " "))
	}
	fmt.Fprintf(sb, "        help) COMPREPLY=( $(compgen -W %q -- \"$cur\") ); return ;;\n", strings.Join(names[:len(names)-1], " "))
	sb.WriteString("    esac\n")
	fmt.Fprintf(sb, "    if [[ \"$cmd\" == completion ]]; then\n        COMPREPLY=( $(compgen -W %q -- \"$cur\") )\n        return\n    fi\n", strings.Join(completionShells, " "))
	sb.WriteString("    if [[ \"$cur\" == -* ]]; then\n        COMPREPLY=( $(compgen -W \"$opts\" -- \"$cur\") )\n    else\n        COMPREPLY=( $(compgen -f -- \"$cur\") )\n    fi\n}\n")
	sb.WriteString("complete -o filenames -o bashdefault -F _teardown teardown\n")
}

// zshText makes a description safe inside a single-quoted _arguments spec.
func zshText(s string) string {
	r := strings.NewReplacer("'", "", "[", "(", "]", ")", ":", " -", "\\", "")
	return r.Replace(s)
}

func writeZsh(sb *strings.Builder) {
	data := completionData()
	sb.WriteString("#compdef teardown\n# zsh completion for teardown (generated by `teardown completion zsh`)\n\n_teardown() {\n    local -a commands\n    commands=(\n")
	for _, c := range data {
		fmt.Fprintf(sb, "        '%s:%s'\n", c.name, zshText(c.summary))
	}
	sb.WriteString("        'help:Show help for a command'\n    )\n")
	sb.WriteString("    if (( CURRENT == 2 )); then\n        _describe -t commands 'teardown command' commands\n        return\n    fi\n")
	sb.WriteString("    case \"${words[2]}\" in\n")
	for _, c := range data {
		fmt.Fprintf(sb, "        %s)\n            _arguments \\\n", c.name)
		for _, f := range c.flags {
			sb.WriteString("                " + zshFlagSpec(f) + " \\\n")
		}
		sb.WriteString("                '(-h --help)'{-h,--help}'[Show help]' \\\n")
		switch c.positional {
		case "file":
			sb.WriteString("                '*:file:_files'\n")
		case "shell":
			fmt.Fprintf(sb, "                '1:shell:(%s)'\n", strings.Join(completionShells, " "))
		default:
			sb.WriteString("                '*: :_nothing'\n")
		}
		sb.WriteString("            ;;\n")
	}
	fmt.Fprintf(sb, "        help)\n            _values 'command' %s\n            ;;\n", strings.Join(sortedCommandNames(), " "))
	sb.WriteString("    esac\n}\n\n_teardown \"$@\"\n")
}

func zshFlagSpec(f flagSpec) string {
	desc := zshText(f.usage)
	action := ""
	switch {
	case f.boolean:
	case len(f.allowed) > 0:
		action = fmt.Sprintf(":%s:(%s)", strings.ToLower(f.meta), strings.Join(f.allowed, " "))
	case f.file:
		action = ":file:_files"
	case f.dir:
		action = ":directory:_files -/"
	default:
		action = ":" + strings.ToLower(f.meta) + ": "
	}
	long := "--" + f.name
	if !f.boolean {
		long += "="
	}
	if f.short == "" {
		return fmt.Sprintf("'%s[%s]%s'", long, desc, action)
	}
	return fmt.Sprintf("'(-%s --%s)'{-%s,--%s}'[%s]%s'", f.short, f.name, f.short, f.name, desc, action)
}

func writeFish(sb *strings.Builder) {
	data := completionData()
	esc := func(s string) string { return strings.ReplaceAll(s, "'", "\\'") }
	sb.WriteString("# fish completion for teardown (generated by `teardown completion fish`)\ncomplete -c teardown -f\n")
	for _, c := range data {
		fmt.Fprintf(sb, "complete -c teardown -n '__fish_use_subcommand' -a %s -d '%s'\n", c.name, esc(c.summary))
	}
	sb.WriteString("complete -c teardown -n '__fish_use_subcommand' -a help -d 'Show help for a command'\n")
	for _, c := range data {
		cond := fmt.Sprintf("-n '__fish_seen_subcommand_from %s'", c.name)
		for _, f := range c.flags {
			line := fmt.Sprintf("complete -c teardown %s -l %s", cond, f.name)
			if f.short != "" {
				line += " -s " + f.short
			}
			switch {
			case f.boolean:
			case len(f.allowed) > 0:
				line += fmt.Sprintf(" -x -a '%s'", strings.Join(f.allowed, " "))
			case f.file:
				line += " -r -F"
			case f.dir:
				line += " -r -a '(__fish_complete_directories)'"
			default:
				line += " -x"
			}
			fmt.Fprintf(sb, "%s -d '%s'\n", line, esc(f.usage))
		}
		switch c.positional {
		case "file":
			fmt.Fprintf(sb, "complete -c teardown %s -F\n", cond)
		case "shell":
			fmt.Fprintf(sb, "complete -c teardown %s -a '%s'\n", cond, strings.Join(completionShells, " "))
		}
	}
	fmt.Fprintf(sb, "complete -c teardown -n '__fish_seen_subcommand_from help' -a '%s'\n", strings.Join(sortedCommandNames(), " "))
}

func writePowerShell(sb *strings.Builder) {
	data := completionData()
	allowed, files, dirs := valueKinds(data)
	q := func(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }
	list := func(items []string) string {
		quoted := make([]string, len(items))
		for i, it := range items {
			quoted[i] = q(it)
		}
		return "@(" + strings.Join(quoted, ", ") + ")"
	}

	sb.WriteString("# PowerShell completion for teardown (generated by `teardown completion powershell`)\n")
	sb.WriteString("Register-ArgumentCompleter -Native -CommandName 'teardown', 'teardown.exe' -ScriptBlock {\n")
	sb.WriteString("    param($wordToComplete, $commandAst, $cursorPosition)\n")
	sb.WriteString("    $subcommands = [ordered]@{\n")
	for _, c := range data {
		fmt.Fprintf(sb, "        %s = %s\n", q(c.name), q(c.summary))
	}
	sb.WriteString("        'help' = 'Show help for a command'\n    }\n")
	sb.WriteString("    $flags = @{\n")
	for _, c := range data {
		fmt.Fprintf(sb, "        %s = %s\n", q(c.name), list(allFlagWords(c)))
	}
	sb.WriteString("    }\n    $values = @{\n")
	keys := make([]string, 0, len(allowed))
	for k := range allowed {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(sb, "        %s = %s\n", q(k), list(allowed[k]))
	}
	sb.WriteString("    }\n")
	fmt.Fprintf(sb, "    $fileFlags = %s\n    $dirFlags = %s\n", list(files), list(dirs))
	sb.WriteString(`    $elements = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })
    $newToken = $wordToComplete -eq ''
    $count = if ($newToken) { $elements.Count } else { $elements.Count - 1 }
    function New-Result($text, $tip) {
        [System.Management.Automation.CompletionResult]::new($text, $text, 'ParameterValue', $(if ($tip) { $tip } else { $text }))
    }
    if ($count -le 1) {
        $subcommands.Keys | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object { New-Result $_ $subcommands[$_] }
        return
    }
    $sub = $elements[1]
    $prev = $elements[$count - 1]
    if ($values.ContainsKey($prev)) {
        $values[$prev] | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object { New-Result $_ $null }
        return
    }
    if ($fileFlags -contains $prev -or $dirFlags -contains $prev) { return }
    if ($sub -eq 'completion') {
        @('bash', 'zsh', 'fish', 'powershell') | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object { New-Result $_ $null }
        return
    }
    if ($sub -eq 'help') {
        $subcommands.Keys | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object { New-Result $_ $subcommands[$_] }
        return
    }
    if ($wordToComplete.StartsWith('-') -and $flags.ContainsKey($sub)) {
        $flags[$sub] | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object { New-Result $_ $null }
    }
}
`)
}
